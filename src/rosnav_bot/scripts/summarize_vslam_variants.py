#!/usr/bin/env python3
"""Summarise benchmark_vslam_variants.sh logs into a markdown table.

usage: summarize_vslam_variants.py <outdir> <world> <out.md> <variant>...
"""
import re
import sys
from pathlib import Path

import numpy as np

LABEL = {'A': 'vslam A (baseline RGB-D)', 'B': 'vslam B (+planar, faster)',
         'C': 'vslam C (+lidar grid, ICP)', 'D': '2d slam_toolbox (lidar)', 'G': 'cartographer (lidar+IMU)',
         'M': 'multisensor (RGB-D+lidar)', 'O': 'orbslam3 (default cfg)'}


def read_pgm(path):
    with open(path, 'rb') as f:
        assert f.readline().strip() == b'P5'
        line = f.readline()
        while line.startswith(b'#'):
            line = f.readline()
        w, h = map(int, line.split())
        f.readline()
        return np.frombuffer(f.read(), dtype=np.uint8).reshape(h, w)


def last(pattern, text, cast=float, default=None):
    m = re.findall(pattern, text)
    return cast(m[-1]) if m else default


def main():
    out, world, md, variants = Path(sys.argv[1]), sys.argv[2], sys.argv[3], sys.argv[4:]
    rows = []
    for v in variants:
        if v.startswith('O-'):
            LABEL.setdefault(v, f'orbslam3 ({v[2:]})')
        log = (out / f'{v}.log').read_text(errors='ignore') if (out / f'{v}.log').exists() else ''
        acc = (out / f'{v}.acc.log').read_text(errors='ignore') if (out / f'{v}.acc.log').exists() else ''
        cov = last(r'coverage=([\d.]+)%', log, float, 0.0)
        known_cells = None
        pgm = out / f'map_{v}.pgm'
        if pgm.exists():
            im = read_pgm(pgm)
            known_cells = int(np.count_nonzero(im != 205))   # 205 = unknown in map_saver output
        rate = last(r'rate=([\d.]+)Hz', log, float, 0.0)
        msgs = last(r'slam_debug_map msgs=(\d+)', log, int, 0)
        jumps = last(r'graph_jumps=(\d+)', log, int, 0)
        maxj = last(r'max_jump=([\d.]+)m', log, float, 0.0)
        resized = len(re.findall(r'MAP RESIZED/SHIFTED', log))
        lc = last(r'loop_closures=(\d+)', log, int, None)
        nodes = last(r'rtab_nodes=(\d+)', log, int, None)
        unstable = len(re.findall(r'SLAM_UNSTABLE', log))
        rmse = last(r'rmse=([\d.]+)m', acc, float, None)
        maxe = last(r'max_err=([\d.]+)m', acc, float, None)
        nud = (out / f'{v}.nudges').read_text().strip() if (out / f'{v}.nudges').exists() else '?'
        goals = len(re.findall(r'Goal succeeded', log))
        rows.append((v, cov, known_cells, msgs, rate, resized, jumps, maxj, lc, nodes, unstable, rmse, maxe, nud, goals))
    f = lambda x, p=2: 'n/a' if x is None else (f'{x:.{p}f}' if isinstance(x, float) else str(x))
    lines = [f'# SLAM variant benchmark — `{world}`', '',
             'Generated by `scripts/benchmark_vslam_variants.sh`; same world, spawn and explorer for every variant. '
             'Higher coverage / map rate and lower jumps / resizes / pose error is better.', '',
             '| Variant | Coverage % | Known cells | /map msgs | Map Hz | Grid resizes | Graph jumps | Max jump m | '
             'Loop closures | RTAB nodes | UNSTABLE | RMSE m | Max err m | Nudges | Nav2 goals ok |',
             '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    for r in rows:
        lines.append(f'| {LABEL.get(r[0], r[0])} | {f(r[1], 1)} | {f(r[2])} | {r[3]} | {f(r[4])} | {r[5]} | {r[6]} | '
                     f'{f(r[7])} | {f(r[8])} | {f(r[9])} | {r[10]} | {f(r[11], 3)} | {f(r[12], 3)} | {r[13]} | {r[14]} |')
    Path(md).write_text('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
